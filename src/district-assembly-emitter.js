function clone(value) {
  return JSON.parse(JSON.stringify(value));
}

function part({
  id,
  assemblyId,
  role,
  material,
  size,
  center,
  hostId,
  supports = [],
  supportedBy = [],
  serviceAccess,
  silhouette,
  traversalIntent = 'decorative',
  routeOrder = null,
  connectsTo = [],
  affordanceCue = 'mass',
  kind = 'structure',
  hazard = false,
  visible = true,
  collisionPolicy = null,
}) {
  return {
    id,
    districtId: 'imperial_foundry',
    assemblyId,
    role,
    material,
    size,
    center,
    hostId,
    supports,
    supportedBy,
    serviceAccess,
    silhouette,
    traversalIntent,
    routeOrder,
    connectsTo,
    affordanceCue,
    kind: hazard ? 'hazard' : kind,
    hazard,
    visible,
    collisionPolicy: collisionPolicy || (visible === false ? 'none' : (traversalIntent === 'walkable' ? 'player' : 'visual_only')),
  };
}

